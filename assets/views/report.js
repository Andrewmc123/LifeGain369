/* ==========================================================================
   views/report.js — the funder report: totals for a period, ready to print
   or hand over as a spreadsheet. Counts only; nobody is named.
   ========================================================================== */

(function () {
  'use strict';

  var esc = Util.esc, state = App.state;
  var barRow = UI.barRow, stat = UI.stat;

  var PERIODS = [
    { v: 'last-month',   t: 'Last month' },
    { v: 'this-month',   t: 'This month so far' },
    { v: 'last-quarter', t: 'Last quarter' },
    { v: 'this-quarter', t: 'This quarter so far' },
    { v: 'this-year',    t: 'This year so far' },
    { v: 'last-30',      t: 'Last 30 days' },
    { v: 'custom',       t: 'Choose dates…' }
  ];

  // The period currently on screen, resolved to real dates.
  function range() {
    var r = state.report;
    if (r.period === 'custom' && r.from && r.to) {
      return r.from <= r.to ? { from: r.from, to: r.to } : { from: r.to, to: r.from };
    }
    return Report.period(r.period === 'custom' ? 'last-30' : r.period);
  }

  function current() {
    var rg = range();
    return Report.build(Store.all(), {
      from: rg.from, to: rg.to, includeSamples: state.report.includeSamples
    });
  }

  function list(title, rows, empty) {
    var max = rows.length ? rows[0].n : 1;
    return '<div class="card"><div class="card-head"><h2>' + esc(title) + '</h2></div>' +
      (rows.length
        ? rows.map(function (x) { return barRow(x.k, x.n, max); }).join('')
        : '<p class="muted mb0">' + esc(empty) + '</p>') +
      '</div>';
  }

  function viewReport() {
    var r = current();
    var rs = state.report;
    var h = '';

    h += '<button class="btn ghost sm mb16 no-print" data-action="nav" data-view="dashboard">← Overview</button>';
    h += '<div class="page-head"><h1>Funder report</h1></div>';
    h += '<p class="lede">' + esc(Doc.fmtDate(r.from)) + ' to ' + esc(Doc.fmtDate(r.to)) +
      ((Store.settings().orgName) ? ' · ' + esc(Store.settings().orgName) : '') + '</p>';

    h += '<div class="card no-print"><div class="toolbar mb0">' +
      '<select id="report-period" aria-label="Period">' +
      PERIODS.map(function (p) {
        return '<option value="' + p.v + '"' + (rs.period === p.v ? ' selected' : '') + '>' + esc(p.t) + '</option>';
      }).join('') + '</select>' +
      (rs.period === 'custom'
        ? '<input type="date" id="report-from" aria-label="From" value="' + esc(rs.from) + '">' +
          '<input type="date" id="report-to" aria-label="To" value="' + esc(rs.to) + '">'
        : '') +
      '<label class="checkline toolbar-check"><input type="checkbox" id="report-samples"' +
      (rs.includeSamples ? ' checked' : '') + '><span>Include sample records</span></label>' +
      '</div>' +
      '<div class="btn-row mt16">' +
      '<button class="btn primary" data-action="report-print">🖨 Print or save as PDF</button>' +
      '<button class="btn" data-action="report-csv">Download spreadsheet (CSV)</button>' +
      '</div>' +
      '<p class="small faint mt16 mb0">Totals only — no names, locations or notes — so this can go to a ' +
      'funder or board without anyone\'s consent being stretched. Archived records still count.' +
      (r.excludedSamples && !rs.includeSamples ? ' ' + r.excludedSamples + ' sample record(s) left out.' : '') +
      '</p></div>';

    h += '<div class="grid cols-4 mb16">' +
      stat(r.reached, 'people reached') +
      stat(r.contacts, 'contacts') +
      stat(r.newPeople, 'new people met') +
      stat(r.housed, 'moved into housing') +
      '</div>';

    h += '<div class="card"><div class="card-head"><h2>Outcomes</h2></div>' +
      '<table class="report-table"><tbody>' +
      Report.headline(r).map(function (row) {
        return '<tr><th scope="row">' + esc(row[0]) + '</th><td>' + esc(row[1]) + '</td></tr>';
      }).join('') +
      '</tbody></table></div>';

    h += '<div class="grid cols-2">' +
      list('Contacts by type', r.contactTypes, 'No contacts in this period.') +
      list('Where people reached were staying', r.situations, 'Nobody reached in this period.') +
      list('Most common needs', r.needs, 'No needs recorded for people reached.') +
      list('Most common barriers', r.barriers, 'No barriers recorded for people reached.') +
      '</div>';

    h += '<p class="small faint">Generated by ' + esc(APP_CONFIG.productName) + ' on ' +
      esc(Doc.fmtDate(Util.todayStr())) + '. "Reached" means at least one logged contact in the period. ' +
      'Engaged, assessed and housed count the dates recorded on each person\'s Plan tab.</p>';
    return h;
  }

  function downloadCSV() {
    var r = current();
    UI.download('outreach-report-' + r.from + '-to-' + r.to + '.csv', UI.toCSV(Report.csv(r)), 'text/csv');
    UI.toast('Report downloaded.');
  }

  Views.report = viewReport;
  Views.reportCSV = downloadCSV;
})();
